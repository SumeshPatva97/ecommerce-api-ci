/**
 * Export writers (CSV / XLSX / PDF) — pure, no DB.
 */
import ExcelJS from 'exceljs';
import { describe, expect, it } from 'vitest';

import {
  CONTENT_TYPES,
  MONEY_FORMAT,
  buildCsv,
  buildPdf,
  buildXlsx,
  csvTextCell,
  formatIndian,
  formatIstDateTime,
  renderExport,
  type ExportDocument,
} from '../../../../src/lib/export/index.js';

function doc(over: Partial<ExportDocument> = {}): ExportDocument {
  return {
    title: 'Store — Sales summary',
    headerLines: [
      ['Filters', '01-11-2026 to 13-11-2026 (IST)'],
      ['Generated by', 'Priya (priya@example.com)'],
    ],
    main: {
      name: 'Sales summary',
      columns: [
        { key: 'name', label: 'Name', type: 'string' },
        { key: 'orders', label: 'Orders', type: 'int' },
        { key: 'amount', label: 'Amount', type: 'money' },
        { key: 'placedAt', label: 'Placed at', type: 'datetime' },
        { key: 'day', label: 'Day', type: 'date' },
      ],
      rows: [
        {
          name: '=HYPERLINK("http://evil")',
          orders: 3,
          amount: '-954.75',
          placedAt: '2026-11-19T06:30:00.000Z',
          day: '2026-11-19',
        },
        { name: '+cmd', orders: 1, amount: '4320.00', placedAt: null, day: null },
        { name: 'Plain, "quoted"', orders: 0, amount: '0.00', placedAt: null, day: null },
      ],
      totals: { orders: 4, amount: '3365.25' },
    },
    notices: ['@note starts with at'],
    footer: 'Prepared for review by a qualified tax professional; verify before filing.',
    generatedAt: new Date('2026-11-19T06:30:00.000Z'),
    ...over,
  };
}

describe('format helpers', () => {
  it('formats Indian digit grouping and IST datetimes', () => {
    expect(formatIndian('432000.00')).toBe('4,32,000.00');
    expect(formatIndian('-12345678.50')).toBe('-1,23,45,678.50');
    expect(formatIndian('999.00')).toBe('999.00');
    expect(formatIstDateTime('2026-11-19T18:29:59.999Z')).toBe('2026-11-19 23:59:59');
    expect(formatIstDateTime('2026-11-19T18:30:00.000Z')).toBe('2026-11-20 00:00:00');
  });
});

describe('CSV writer', () => {
  it('guards formula injection on text cells but keeps negative numbers numeric', () => {
    const csv = buildCsv(doc()).toString('utf8');
    expect(csv.charCodeAt(0)).toBe(0xfeff);
    const lines = csv.slice(1).split('\r\n');
    expect(lines[0]).toBe('# Store — Sales summary');
    expect(lines).toContain('# Filters: 01-11-2026 to 13-11-2026 (IST)');
    expect(lines).toContain('# Note: @note starts with at');
    const header = lines.indexOf('Name,Orders,Amount,Placed at (IST),Day');
    expect(header).toBeGreaterThan(0);
    expect(lines[header + 1]).toBe(
      `"'=HYPERLINK(""http://evil"")",3,-954.75,2026-11-19 12:00:00,2026-11-19`,
    );
    expect(lines[header + 2]).toBe("'+cmd,1,4320.00,,");
    expect(lines[header + 3]).toBe('"Plain, ""quoted""",0,0.00,,');
    expect(lines[header + 4]).toBe('Total,4,3365.25,,');
    expect(csv).toContain('# Prepared for review');
  });

  it('guards each injection prefix and omits the header block on request', () => {
    for (const prefix of ['=', '+', '-', '@', '\t', '\r']) {
      expect(csvTextCell(`${prefix}x`).replace(/^"/, '').startsWith("'")).toBe(true);
    }
    const csv = buildCsv(doc(), { includeHeader: false }).toString('utf8');
    expect(csv.slice(1).startsWith('Name,Orders')).toBe(true);
    expect(csv).not.toContain('# ');
  });
});

describe('XLSX writer', () => {
  it('writes numeric money cells with a 2-dp format, IST dates and guarded text', async () => {
    const buffer = await buildXlsx(
      doc({
        extraSheets: [
          {
            name: 'State-wise',
            columns: [{ key: 's', label: 'State', type: 'string' }],
            rows: [{ s: '27' }],
          },
        ],
      }),
    );
    const wb = new ExcelJS.Workbook();
    await wb.xlsx.load(buffer as unknown as ArrayBuffer);
    expect(wb.worksheets.map((w) => w.name)).toEqual(['Report', 'State-wise', 'Filters & Info']);
    const ws = wb.getWorksheet('Report');
    if (ws === undefined) throw new Error('missing sheet');
    expect(ws.getRow(1).getCell(4).value).toBe('Placed at (IST)');
    const row = ws.getRow(2);
    expect(row.getCell(1).value).toBe('\'=HYPERLINK("http://evil")');
    expect(row.getCell(2).value).toBe(3);
    expect(row.getCell(3).value).toBe(-954.75);
    expect(row.getCell(3).numFmt).toBe(MONEY_FORMAT);
    const placed = row.getCell(4).value;
    expect(placed).toBeInstanceOf(Date);
    // Wall-clock IST (12:00) stored as the Excel date.
    expect((placed as Date).toISOString()).toBe('2026-11-19T12:00:00.000Z');
    expect(ws.getRow(5).getCell(1).value).toBe('Total');
    expect(ws.getRow(5).font.bold).toBe(true);
    expect(ws.autoFilter).toBeDefined();
    const info = wb.getWorksheet('Filters & Info');
    expect(info?.getRow(2).getCell(2).value).toBe('Store — Sales summary');
  });
});

describe('PDF writer & renderExport', () => {
  it('produces a PDF and maps formats to content types', async () => {
    const pdf = await buildPdf(doc());
    expect(pdf.subarray(0, 5).toString('latin1')).toBe('%PDF-');
    const many = await buildPdf(
      doc({
        main: {
          name: 'x',
          columns: [{ key: 'n', label: 'N', type: 'int' }],
          rows: Array.from({ length: 150 }, (_, i) => ({ n: i })),
        },
      }),
    );
    expect(many.length).toBeGreaterThan(pdf.length / 2);
    for (const format of ['csv', 'xlsx', 'pdf'] as const) {
      const out = await renderExport(format, doc());
      expect(out.contentType).toBe(CONTENT_TYPES[format]);
      expect(out.extension).toBe(format);
      expect(out.body.length).toBeGreaterThan(0);
    }
    expect(CONTENT_TYPES.xlsx).toBe(
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    );
  });
});
